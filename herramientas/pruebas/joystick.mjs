// El joystick en el emulador de Meta: anda hacia delante y gira 30°, y al volver al día se recoloca. Uso: node herramientas/pruebas/joystick.mjs
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('C:/Users/NIBI/Documents/GitHub/presupuesya-maqueta/node_modules/playwright-core');
const nav = await chromium.launch({ channel: 'chrome', args: ['--use-angle=d3d11'] });
const pag = await nav.newPage({ viewport: { width: 1280, height: 720 } });
const errores = [];
pag.on('pageerror', e => errores.push(e.message));
pag.on('console', m => { if (m.type() === 'error' && !m.text().includes('404')) errores.push(m.text()); });
await pag.goto(`http://127.0.0.1:18765/?emular&v=${Date.now()}`);
await pag.waitForFunction(() => window.__unake && !document.getElementById('btnAR').disabled, null, { timeout: 40000 });
await pag.click('#btnAR');
await pag.waitForTimeout(3000);
const cab = () => pag.evaluate(() => { const o = window.__unake.obj(); return { p: o.xr.cabeza.toArray().map(v => +v.toFixed(2)), f: o.xr.adelante.toArray().map(v => +v.toFixed(2)) }; });
console.log('antes', JSON.stringify(await cab()));
await pag.evaluate(() => window.__unake.obj().xr.permitirMovimiento(true));
await pag.evaluate(() => window.__xrEmulado.controllers.left.updateAxes('thumbstick', 0, -1));
await pag.waitForTimeout(1000);
await pag.evaluate(() => window.__xrEmulado.controllers.left.updateAxes('thumbstick', 0, 0));
console.log('tras 1 s hacia delante', JSON.stringify(await cab()));
await pag.evaluate(() => window.__xrEmulado.controllers.right.updateAxes('thumbstick', 1, 0));
await pag.waitForTimeout(200);
await pag.evaluate(() => window.__xrEmulado.controllers.right.updateAxes('thumbstick', 0, 0));
await pag.waitForTimeout(200);
console.log('tras girar a la derecha', JSON.stringify(await cab()));
await pag.evaluate(() => window.__unake.obj().xr.permitirMovimiento(false));
await pag.waitForTimeout(300);
console.log('de vuelta a tu sitio', JSON.stringify(await cab()));
console.log(errores.length ? errores.slice(0, 6).join('\n') : 'sin errores');
await nav.close();
